-- Public tenant form: token-scoped read. It intentionally does NOT expose office-only fields.
create or replace function public.get_contract_intake_public(p_token text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare r public.contract_intakes;
begin
  begin
    select * into r from public.contract_intakes where public_token = p_token::uuid;
  exception when invalid_text_representation then
    return null;
  end;
  if r.id is null then return null; end if;
  return jsonb_build_object(
    'id',r.id,'status',r.status,
    'tenant_first_name',r.tenant_first_name,'tenant_last_name',r.tenant_last_name,
    'tenant_date_of_birth',r.tenant_date_of_birth,'tenant_id_number',r.tenant_id_number,
    'occupant_count',r.occupant_count,'phone',r.phone,'email',r.email,
    'id_front_path',r.id_front_path,'id_back_path',r.id_back_path,
    'has_additional_tenant',r.has_additional_tenant,
    'additional_tenant_first_name',r.additional_tenant_first_name,
    'additional_tenant_last_name',r.additional_tenant_last_name,
    'additional_tenant_date_of_birth',r.additional_tenant_date_of_birth,
    'additional_tenant_id_number',r.additional_tenant_id_number,
    'additional_id_front_path',r.additional_id_front_path,
    'additional_id_back_path',r.additional_id_back_path
  );
end;
$$;

create or replace function public.save_contract_intake_public(p_token text,p_payload jsonb,p_complete boolean default false)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare r public.contract_intakes;
begin
  begin
    select * into r from public.contract_intakes where public_token = p_token::uuid for update;
  exception when invalid_text_representation then
    raise exception 'Invalid tenant link';
  end;
  if r.id is null then raise exception 'Tenant link not found'; end if;
  if r.status in ('assigned','contract_ready','completed','archived') then raise exception 'This tenant form is already closed'; end if;

  update public.contract_intakes set
    tenant_first_name=nullif(trim(p_payload->>'tenant_first_name'),''),
    tenant_last_name=nullif(trim(p_payload->>'tenant_last_name'),''),
    tenant_date_of_birth=nullif(p_payload->>'tenant_date_of_birth','')::date,
    tenant_id_number=nullif(trim(p_payload->>'tenant_id_number'),''),
    occupant_count=nullif(p_payload->>'occupant_count','')::integer,
    phone=nullif(trim(p_payload->>'phone'),''),
    email=nullif(trim(p_payload->>'email'),''),
    id_front_path=nullif(p_payload->>'id_front_path',''),
    id_back_path=nullif(p_payload->>'id_back_path',''),
    has_additional_tenant=coalesce((p_payload->>'has_additional_tenant')::boolean,false),
    additional_tenant_first_name=nullif(trim(p_payload->>'additional_tenant_first_name'),''),
    additional_tenant_last_name=nullif(trim(p_payload->>'additional_tenant_last_name'),''),
    additional_tenant_date_of_birth=nullif(p_payload->>'additional_tenant_date_of_birth','')::date,
    additional_tenant_id_number=nullif(trim(p_payload->>'additional_tenant_id_number'),''),
    additional_id_front_path=nullif(p_payload->>'additional_id_front_path',''),
    additional_id_back_path=nullif(p_payload->>'additional_id_back_path',''),
    status=case when p_complete then 'submitted' else 'draft' end,
    submitted_at=case when p_complete then coalesce(submitted_at,now()) else submitted_at end
  where id=r.id
  returning * into r;

  return public.get_contract_intake_public(p_token);
end;
$$;

revoke all on function public.get_contract_intake_public(text) from public;
revoke all on function public.save_contract_intake_public(text,jsonb,boolean) from public;
grant execute on function public.get_contract_intake_public(text) to anon,authenticated;
grant execute on function public.save_contract_intake_public(text,jsonb,boolean) to anon,authenticated;

