create or replace function public.assign_contract_intake(
  p_intake_id bigint,
  p_building_id bigint,
  p_unit_id bigint,
  p_monthly_rent numeric default 0,
  p_additional_costs numeric default 0
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  r public.contract_intakes;
  v_tenant_id bigint;
begin
  select * into r from public.contract_intakes where id=p_intake_id for update;
  if r.id is null then raise exception 'Contract intake not found'; end if;
  if r.submitted_at is null and r.status not in ('submitted','assigned','contract_ready','completed') then
    raise exception 'Tenant must submit the form before assignment';
  end if;
  if not exists(select 1 from public.buildings where id=p_building_id) then raise exception 'Building not found'; end if;
  if not exists(select 1 from public.units where id=p_unit_id and building_id=p_building_id) then raise exception 'Selected unit does not belong to the selected building'; end if;

  v_tenant_id:=r.tenant_id;
  if v_tenant_id is null then
    insert into public.tenants(name,phone,email,base_rent,additional_costs,rent,active)
    values(trim(concat_ws(' ',r.tenant_first_name,r.tenant_last_name)),coalesce(r.phone,''),coalesce(r.email,''),coalesce(p_monthly_rent,0),coalesce(p_additional_costs,0),coalesce(p_monthly_rent,0)+coalesce(p_additional_costs,0),true)
    returning id into v_tenant_id;
  else
    update public.tenants set
      name=trim(concat_ws(' ',r.tenant_first_name,r.tenant_last_name)),phone=coalesce(r.phone,''),email=coalesce(r.email,''),
      base_rent=coalesce(p_monthly_rent,0),additional_costs=coalesce(p_additional_costs,0),rent=coalesce(p_monthly_rent,0)+coalesce(p_additional_costs,0),active=true
    where id=v_tenant_id;
  end if;

  delete from public.tenant_units where tenant_id=v_tenant_id;
  insert into public.tenant_units(tenant_id,unit_id) values(v_tenant_id,p_unit_id);

  update public.contract_intakes set tenant_id=v_tenant_id,building_id=p_building_id,unit_id=p_unit_id,
    monthly_rent=coalesce(p_monthly_rent,0),additional_costs=coalesce(p_additional_costs,0),
    status=case when status='contract_ready' then 'contract_ready' else 'assigned' end
  where id=p_intake_id;
  return v_tenant_id;
end;
$$;
revoke all on function public.assign_contract_intake(bigint,bigint,bigint,numeric,numeric) from public;
grant execute on function public.assign_contract_intake(bigint,bigint,bigint,numeric,numeric) to authenticated;

